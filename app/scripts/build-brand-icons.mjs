/**
 * Derives the shipped brand assets from the delivered artwork in `brand/`.
 *
 * The delivered file is a 200x200 tile with app-icon padding: the glyph covers
 * only 63% x 72% of the frame, which dissolves into a blob at 16px favicon size
 * and makes a `size-8` box render a ~23px mark. Both outputs re-frame it.
 *
 * Run: npm run brand:icons
 */
import { readFileSync, writeFileSync } from 'node:fs'

const SRC = 'brand/logo-source.svg'
/** The full-bleed tile background — a shade lighter than `--sidebar`. */
const BG = '<path d="M0 0H200V200H0V0Z" fill="#1F1F1F"/>'
/** Measured with getBBox() in a real renderer, so filter/shadow spread is excluded. */
const GLYPH = { cx: 102.3056, cy: 101.2412, w: 126.7382, h: 144.5424 }
const FRAME = 200
/** Fraction of the tile the glyph should cover. Bounded by the drop shadow, which
    falls below and right of the glyph and would clip if pushed much further. */
const TILE_FILL = 1.15
const MARK_FILL = 0.88

const src = readFileSync(SRC, 'utf8')
const bgAt = src.indexOf(BG)
const defsAt = src.indexOf('<defs>')
if (bgAt < 0 || defsAt < 0) {
  throw new Error(`${SRC}: expected a full-bleed background path and a <defs> block`)
}
const afterBg = bgAt + BG.length

// Between the background and <defs> sits the mark plus the closing tag of the
// outer clip group. Split that last </g> off so it stays outermost.
const mid = src.slice(afterBg, defsAt)
const lastClose = mid.lastIndexOf('</g>')
const mark = mid.slice(0, lastClose)
const clipClose = mid.slice(lastClose)

// --- favicon.svg — the tile. Scale the mark about its own centre, then re-centre
// it in the frame, leaving the background full-bleed.
const t =
  `translate(${FRAME / 2} ${FRAME / 2}) scale(${TILE_FILL}) ` +
  `translate(${-GLYPH.cx} ${-GLYPH.cy})`
writeFileSync(
  'public/favicon.svg',
  src.slice(0, afterBg) +
    `\n<!-- Generated by scripts/build-brand-icons.mjs — do not hand-edit.\n` +
    `     Mark scaled ${TILE_FILL}x about its centre; the delivered padding is\n` +
    `     app-icon padding and dissolves at 16px. Background left full-bleed. -->\n` +
    `<g transform="${t}">` + mark + '</g>' + clipClose +
    src.slice(defsAt),
)

// --- logo-mark.svg — the same mark with no tile, for in-app chrome. Crop the
// viewBox to the glyph rather than scaling the art, so the box size is honest.
const side = GLYPH.h / MARK_FILL
const vb = [GLYPH.cx - side / 2, GLYPH.cy - side / 2, side, side]
  .map((n) => Number(n.toFixed(2)))
  .join(' ')
writeFileSync(
  'public/logo-mark.svg',
  src
    .replace(
      BG,
      '<!-- Generated by scripts/build-brand-icons.mjs — do not hand-edit.\n' +
        '     Tile background removed: this mark sits on the app surface. -->',
    )
    .replace('viewBox="0 0 200 200"', `viewBox="${vb}"`),
)

console.log(`✓ public/favicon.svg    mark scaled ${TILE_FILL}x inside its tile`)
console.log(`✓ public/logo-mark.svg  viewBox="${vb}" — glyph fills ${MARK_FILL * 100}% of the box`)
